from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from decimal import Decimal
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.models.case import CaseCategory
from app.services.ai import MockAIClient


COMPANIES = {
    "refund": ["BrightMart", "QuickCart", "MetroStyle", "GadgetHub", "FreshBox"],
    "warranty": ["Northstar Appliances", "Apex Electronics", "Summit Tools", "Harbor Devices", "Oakridge Furniture"],
    "travel": ["SkyWay Air", "Coastal Rail", "MetroStay Hotels", "BlueWing Airlines", "UrbanRide Travel"],
}

REASONS = {
    "refund": "refund",
    "warranty": "warranty",
    "travel": "travel",
}


def build_dataset() -> list[dict[str, str]]:
    records = []
    for category, companies in COMPANIES.items():
        for index in range(15):
            company = companies[index % len(companies)]
            amount = Decimal("75.00") + Decimal(index * 18)
            date = f"2026-08-{(index % 28) + 1:02d}"
            if category == "refund":
                text = (
                    f"Receipt from {company}. Purchase date: {date}. Amount: ${amount}. "
                    "Email denial refused refund after the item was returned."
                )
            elif category == "warranty":
                text = (
                    f"Company: {company}. Warranty claim denied on {date}. Amount: ${amount}. "
                    "Receipt and warranty attached."
                )
            else:
                text = (
                    f"Airline: {company}. Baggage delay reimbursement request dated {date}. "
                    f"Amount: ${amount}. Itinerary and email attached."
                )
            records.append(
                {
                    "name": f"{category}_{index + 1:02d}",
                    "category": category,
                    "company": company,
                    "amount": f"{amount:.2f}",
                    "date": date,
                    "reason_contains": REASONS[category],
                    "text": text,
                }
            )
    return records


def main() -> int:
    parser = argparse.ArgumentParser(description="Benchmark Resolviq mock extraction on known-answer cases.")
    parser.add_argument("--output-dir", default="evaluation/results", help="Directory for CSV and JSON evidence.")
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    dataset = build_dataset()
    client = MockAIClient()

    rows = []
    started = time.perf_counter()
    validation_successes = 0
    for record in dataset:
        case_started = time.perf_counter()
        analysis = client.analyze_documents(CaseCategory(record["category"]), record["text"])
        elapsed_ms = (time.perf_counter() - case_started) * 1000
        validation_successes += 1
        company_ok = analysis.company == record["company"]
        amount_ok = analysis.disputed_amount == Decimal(record["amount"])
        date_ok = any(str(item.date) == record["date"] for item in analysis.important_dates)
        reason_ok = record["reason_contains"] in analysis.dispute_reason.lower()
        rows.append(
            {
                "name": record["name"],
                "category": record["category"],
                "company_expected": record["company"],
                "company_actual": analysis.company,
                "company_ok": company_ok,
                "amount_expected": record["amount"],
                "amount_actual": str(analysis.disputed_amount),
                "amount_ok": amount_ok,
                "date_expected": record["date"],
                "date_ok": date_ok,
                "reason_ok": reason_ok,
                "processing_ms": round(elapsed_ms, 4),
            }
        )

    total_elapsed = time.perf_counter() - started
    field_checks = len(rows) * 4
    passed_field_checks = sum(
        int(row["company_ok"]) + int(row["amount_ok"]) + int(row["date_ok"]) + int(row["reason_ok"])
        for row in rows
    )
    summary = {
        "dataset": "deterministic known-answer documents generated by backend/scripts/benchmark_extraction.py",
        "documents": len(rows),
        "categories": sorted(COMPANIES),
        "documents_per_category": 15,
        "classification_accuracy": None,
        "classification_note": "Resolviq does not implement autonomous document classification; users select refund, warranty, or travel before analysis.",
        "field_extraction_accuracy": passed_field_checks / field_checks,
        "validation_success_rate": validation_successes / len(rows),
        "total_processing_seconds": total_elapsed,
        "average_processing_ms": sum(row["processing_ms"] for row in rows) / len(rows),
        "field_checks": field_checks,
        "passed_field_checks": passed_field_checks,
    }

    with (output_dir / "resolviq_extraction_benchmark.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    with (output_dir / "resolviq_extraction_summary.json").open("w", encoding="utf-8") as file:
        json.dump(summary, file, indent=2)

    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
